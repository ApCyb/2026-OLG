function f=fast_config(c,prepare)
% Translate the unified configuration to the October 26 Q-mode kernels.
if nargin<2, prepare=true; end
s=c.search; f=struct('protocolVersion','unified_fex_q_modes_v4_20261026', ...
    'lambda',c.model.lambda,'sigma',c.model.sigma,'beta',c.model.beta, ...
    'Q',s.Q,'stateStep',s.stateStep,'bRange',s.bRange,'bStep',s.bStep, ...
    'includeLowerEndpoint',s.includeLowerEndpoint,'burn',c.horizon.transient, ...
    'sample',c.horizon.cheap-c.horizon.transient,'confirmHorizon',c.horizon.ftle, ...
    'KThreshold',c.zeroOne.threshold,'LEThreshold',c.detector.ftleThreshold, ...
    'LEScale',0.05,'cValues',c.zeroOne.cValues,'lagFraction',c.zeroOne.lagFraction, ...
    'rosenstein',c.rosenstein,'maxState',c.detector.maxState, ...
    'phaseMode','full','phaseOrder',s.stateOrder,'phaseSeed',s.stateSeed, ...
    'phaseChunkSize',s.stateChunkSize,'phaseBatchSize',s.stateBatchSize, ...
    'phaseCheckpointSeconds',s.stateCheckpointSeconds,'phaseProgressSeconds',s.stateProgressSeconds, ...
    'phaseScan',s.phaseScan,'firstHitBatchSize',s.firstHitBatchSize, ...
    'savePhaseRecords',strcmp(s.phaseScan,'full'),'basinMaxPeriod',c.basin.maxPeriod, ...
    'basinRepeats',c.basin.repeats,'basinPeriodTol',c.basin.periodTolerance, ...
    'basinClusterTol',c.basin.clusterTolerance,'resume',c.output.resume, ...
    'seed',s.seed,'population',s.population,'F',s.mutation,'CR',s.crossover, ...
    'strategy',s.strategy,'snapToGrid',s.snapToGrid,'maxEvaluations',s.maxEvaluations, ...
    'repetitions',s.repetitions,'gridMode',s.gridMode, ...
    'gridFirstProbeCount',s.gridFirstProbeCount,'gridExtraProbes',s.gridExtraProbes, ...
    'gridProbesPerRegime',s.gridProbesPerRegime,'historicalCandidateB',s.historicalCandidateB, ...
    'gridRegimeBreaks',s.gridRegimeBreaks,'integrator',c.runtime.integrator, ...
    'zeroOneBackend',c.runtime.zeroOneBackend,'diagnostics',s.diagnostics, ...
    'condn',c.condn,'usePhaseLookup',true,'cacheParameters',s.cacheParameters, ...
    'poolType',c.parallel.poolType,'useParallel',c.parallel.enabled, ...
    'workers',c.parallel.workers,'resizePool',c.parallel.resizePool, ...
    'evaluationMode','staged');
if ~isempty(s.stateGridSize), f.stateStep=diff(s.Q,1,2)'./(s.stateGridSize-1); end
f.rosenstein.maxPoints=c.horizon.ftle;
f=olg.fast.olg_prepare_modes(f);
if prepare, f=olg.fast.olg_prepare_fast(f); end
end
